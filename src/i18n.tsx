const DICTS: Record<Lang, Dict> = { pt, en, zh, hi, es, fr };

export type TFunc = (key: string, vars?: Record<string, string | number>) => string;

interface I18nValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: TFunc;
}

const I18nContext = createContext<I18nValue>({
  lang: 'pt',
  setLang: () => {},
  t: (k) => k,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem('dockdesk-lang');
    return (saved && saved in DICTS ? saved : 'pt') as Lang;
  });

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    localStorage.setItem('dockdesk-lang', l);
  }, []);

  // mantém o menu da bandeja no mesmo idioma
  useEffect(() => {
    window.dockdesk.settings.setLang(lang).catch(() => {});
  }, [lang]);

  const t = useCallback<TFunc>(
    (key, vars) => {
      let text = DICTS[lang][key] ?? DICTS.pt[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          text = text.replaceAll(`{${k}}`, String(v));
        }
      }
      return text;
    },
    [lang]
  );

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
